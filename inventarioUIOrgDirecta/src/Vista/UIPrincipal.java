    void listar() {
        try {
            modelo.setRowCount(0);
            int total = controlador.totalRegistros();
            for (int i = 0; i < total; i++) {
                Producto p = controlador.leer(i);
                if (p != null && p.estado) {
                    modelo.addRow(new Object[]{p.id, p.nombre, p.descripcion, p.existencia, p.estado});
                }
            }
        } catch (Exception ex) {
            ex.printStackTrace();
        }
    }

