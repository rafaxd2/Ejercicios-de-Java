    private void tblProductosMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_tblProductosMouseClicked
        // TODO add your handling code here:
        int fila = this.tblProductos.getSelectedRow();

        if (fila == -1) {
            return;
        }

        try {
            // ... Todo tu código de búsqueda que pusimos antes ...
            int idSeleccionado = Integer.parseInt(this.tblProductos.getValueAt(fila, 0).toString());
            int total = controlador.totalRegistros();
            for (int i = 0; i < total; i++) {
                Producto p = controlador.leer(i);
                if (p != null && p.estado && p.id == idSeleccionado) {
                    txtId.setText(String.valueOf(p.id));
                    txtNombre.setText(p.nombre);
                    txtDescripcion.setText(p.descripcion);
                    txtExistencia.setText(String.valueOf(p.existencia));
                    break;
                }
            }

        } catch (IOException ex) {
            // REEMPLAZA LA LÍNEA DEL ERROR POR ESTA:
            ex.printStackTrace();
        }
    }//GEN-LAST:event_tblProductosMouseClicked

    private void btnBuscarMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_btnBuscarMouseClicked
        // TODO add your handling code here:
        if (this.txtId.getText().trim().isEmpty()) {
            JOptionPane.showMessageDialog(this, "Por favor, ingrese un ID para buscar.");
            return;
        }

        try {
            int idBuscar = Integer.parseInt(this.txtId.getText().trim());
            int filasTabla = this.tblProductos.getRowCount(); // Obtenemos cuántas filas hay REALMENTE en la tabla

            // 2. Recorremos la tabla visual fila por fila
            for (int i = 0; i < filasTabla; i++) {
                int idEnTabla = Integer.parseInt(this.tblProductos.getValueAt(i, 0).toString());

                // 3. Si el ID coincide con el que buscamos
                if (idBuscar == idEnTabla) {
                    // Llenamos los campos de texto con los datos de esa fila de la tabla
                    txtNombre.setText(this.tblProductos.getValueAt(i, 1).toString());
                    txtDescripcion.setText(this.tblProductos.getValueAt(i, 2).toString());
                    txtExistencia.setText(this.tblProductos.getValueAt(i, 3).toString());

                    // Seleccionamos visualmente la fila encontrada
                    this.tblProductos.setRowSelectionInterval(i, i);
                    return; // Terminamos el método exitosamente
                }
            }

            // Si termina el ciclo y no entró al 'if', significa que no existe o está eliminado (false)
            JOptionPane.showMessageDialog(this, "No se encuentra el registro activo con ese ID");

        } catch (NumberFormatException e) {
            JOptionPane.showMessageDialog(this, "El ID debe ser un número válido.");
        } catch (Exception ex) {
            ex.printStackTrace();
        }
    }//GEN-LAST:event_btnBuscarMouseClicked

