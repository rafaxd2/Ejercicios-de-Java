    private void btnEliminarMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_btnEliminarMouseClicked
        // TODO add your handling code here:
        try {
            int fila = this.tblProductos.getSelectedRow();
            if (fila == -1) {
                JOptionPane.showMessageDialog(this, "Seleccione un registro de la tabla para eliminar.");
                return;
            }

            // Obtener el ID de la fila visual de la tabla
            int idEliminar = Integer.parseInt(this.tblProductos.getValueAt(fila, 0).toString());

            // El Controlador busca su posición exacta en el archivo .dat y hace el borrado lógico
            controlador.eliminar(idEliminar);

            listar(); // Refrescar tabla visual
        } catch (Exception ex) {
            ex.printStackTrace();
        }
    }//GEN-LAST:event_btnEliminarMouseClicked

    private void btnActualizarMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_btnActualizarMouseClicked
        // TODO add your handling code here:
        try {
            int fila = this.tblProductos.getSelectedRow();
            if (fila == -1) {
                JOptionPane.showMessageDialog(this, "Seleccione un registro de la tabla para actualizar.");
                return;
            }

            // Obtener el ID original del registro seleccionado antes de que el usuario lo edite en los inputs
            int idOriginal = Integer.parseInt(this.tblProductos.getValueAt(fila, 0).toString());

            // El Controlador busca el índice físico en el archivo y sobreescribe
            controlador.actualizar(
                    idOriginal,
                    Integer.parseInt(txtId.getText()),
                    txtNombre.getText(),
                    txtDescripcion.getText(),
                    Integer.parseInt(txtExistencia.getText())
            );

            listar();
        } catch (Exception ex) {
            ex.printStackTrace();
        }
    }//GEN-LAST:event_btnActualizarMouseClicked

